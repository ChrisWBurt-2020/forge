use std::borrow::Cow;
use std::collections::{HashMap, HashSet};

use super::print::{Element, Print};
use super::{Fragment, Ident, Module};
use crate::plugin::{self, Err};

/// One level of indentation.
const INDENT: &str = "  ";

/// The number of columns comments and imports are wrapped at.
const WIDTH: usize = 80;

/// The first lines of every file. They mark it as generated and turn off
/// ESLint.
pub const PREAMBLE: &str = "// Code generated by forge. DO NOT EDIT.\n/* eslint-disable */\n\n";

/// A TypeScript file: its module and the lines printed to it.
///
/// Print lines with [`p!`](super::p) and [`doc`](File::doc). The file
/// renders them only once it knows every import, so it can give
/// conflicting names aliases.
#[derive(Clone, Debug)]
pub struct File {
    module: Module,
    body: Fragment,
    /// How many levels to indent the lines printed next.
    depth: usize,
}

impl File {
    /// Returns an empty file at `module`.
    pub fn new(module: Module) -> File {
        File {
            module,
            body: Fragment::new(),
            depth: 0,
        }
    }

    /// Returns the module of the file.
    pub fn module(&self) -> &Module {
        &self.module
    }

    /// Returns an identifier declared in this file.
    pub fn ident(&self, name: impl Into<Cow<'static, str>>) -> Ident {
        self.module.ident(name)
    }

    /// Prints a line: the file's indentation, each part, then a line break.
    /// If the parts print nothing but empty text, the line is blank, with no
    /// indentation. [`p!`](super::p) calls this.
    ///
    /// Only the start of the line is indented, so parts shouldn't contain
    /// line breaks.
    pub fn line(&mut self, parts: &[&dyn Print]) {
        let line = Fragment::of(parts);
        if !line.is_empty() {
            self.body.text(&INDENT.repeat(self.depth));
            self.body.append(line);
        }
        self.body.text("\n");
    }

    /// Calls `f` with the file indented one more level, so the lines and
    /// comments it prints get two more spaces.
    pub fn indent(&mut self, f: impl FnOnce(&mut File)) {
        self.depth += 1;
        f(self);
        self.depth -= 1;
    }

    /// Prints `text` as a JSDoc comment at the file's indentation. It trims
    /// the text, prints each line after ` * `, and wraps words to fit in 80
    /// columns, giving a word longer than a line a line of its own. It
    /// escapes `*/` so the text can't end the comment early, and prints
    /// nothing for empty text.
    ///
    /// ```text
    /// /**
    ///  * Returns a pet.
    ///  *
    ///  * It is looked up by its ID.
    ///  */
    /// ```
    pub fn doc(&mut self, text: &str) {
        let body = text.replace("*/", "*\\/");
        let body = body.trim();
        if body.is_empty() {
            return;
        }
        let tab = INDENT.repeat(self.depth);
        let prefix = format!("{tab} * ");
        self.body.text(&format!("{tab}/**\n"));
        for line in body.replace("\r\n", "\n").split('\n') {
            for wrapped in wrap(&prefix, line) {
                self.body.text(&wrapped);
                self.body.text("\n");
            }
        }
        self.body.text(&format!("{tab} */\n"));
    }

    /// Returns the content of the file as text, as
    /// [`content`](plugin::File::content) describes it.
    pub(super) fn render(&self) -> String {
        if self.body.is_empty() {
            return String::new();
        }
        let imports = self.imports();
        let aliases = self.aliases(&imports);
        let mut b = String::from(PREAMBLE);
        let declarations = self.declarations(&imports, &aliases);
        if !declarations.is_empty() {
            b.push_str(&declarations);
            b.push('\n');
        }
        for element in self.body.elements() {
            match element {
                Element::Text(text) => b.push_str(text),
                Element::Ident(id) => b.push_str(&self.name(id, &aliases)),
            }
        }
        let len = b.trim_end_matches('\n').len();
        b.truncate(len);
        b.push('\n');
        b
    }

    /// Reports whether `id` is declared in this file or in no module, so
    /// the file doesn't import it.
    fn is_local(&self, id: &Ident) -> bool {
        id.module == self.module || id.module.as_str().is_empty()
    }

    /// Returns the identifiers the file imports, sorted with packages first,
    /// then generated files, each by specifier, then by name and alias.
    /// Each identifier is reduced to the name it's imported by, such as
    /// `Temporal` for `Temporal.Instant`, with `type_only` cleared.
    /// `Imports::values` records which ones are used as values.
    fn imports(&self) -> Imports {
        let mut values = HashSet::new();
        let mut types = HashSet::new();
        for element in self.body.elements() {
            let Element::Ident(id) = element else { continue };
            if self.is_local(id) {
                continue;
            }
            let key = import_key(id);
            if id.type_only {
                types.insert(key);
            } else {
                values.insert(key);
            }
        }
        let mut sorted: Vec<Ident> = values.iter().cloned().collect();
        sorted.extend(types.into_iter().filter(|id| !values.contains(id)));
        sorted.sort_by_cached_key(|id| {
            (
                rank(&id.module),
                self.specifier(&id.module),
                id.name.clone(),
                id.alias.clone(),
            )
        });
        Imports { sorted, values }
    }

    /// Picks the name the file uses for each imported identifier: its alias
    /// if it has one, otherwise its own name. It appends `$` until the name
    /// clashes with neither a name the file declares nor an earlier import,
    /// going through the imports in sorted order.
    fn aliases(&self, imports: &Imports) -> HashMap<Ident, String> {
        let mut taken: HashSet<String> = HashSet::new();
        for element in self.body.elements() {
            if let Element::Ident(id) = element
                && self.is_local(id)
            {
                taken.insert(root(&id.name).to_owned());
            }
        }
        let mut aliases = HashMap::with_capacity(imports.sorted.len());
        for id in &imports.sorted {
            let mut name = id.alias.as_deref().unwrap_or(&id.name).to_owned();
            while taken.contains(&name) {
                name.push('$');
            }
            taken.insert(name.clone());
            aliases.insert(id.clone(), name);
        }
        aliases
    }

    /// Returns the name the file refers to `id` by.
    fn name<'a>(&self, id: &'a Ident, aliases: &HashMap<Ident, String>) -> Cow<'a, str> {
        if self.is_local(id) {
            return Cow::Borrowed(&id.name);
        }
        let name = &aliases[&import_key(id)];
        match id.name.split_once('.') {
            Some((_, rest)) => Cow::Owned(format!("{name}.{rest}")),
            None => Cow::Owned(name.clone()),
        }
    }

    /// Returns the import declarations of the file.
    fn declarations(&self, imports: &Imports, aliases: &HashMap<Ident, String>) -> String {
        let mut b = String::new();
        let mut previous: Option<&Module> = None;
        for group in imports.sorted.chunk_by(|a, b| a.module == b.module) {
            let module = &group[0].module;
            if previous.is_some_and(|previous| rank(previous) != rank(module)) {
                b.push('\n');
            }
            previous = Some(module);
            let all_types = group.iter().all(|id| !imports.values.contains(id));
            let names: Vec<String> = group
                .iter()
                .map(|id| {
                    let mut name = id.name.to_string();
                    let alias = &aliases[id];
                    if *alias != name {
                        name = format!("{name} as {alias}");
                    }
                    if !all_types && !imports.values.contains(id) {
                        name = format!("type {name}");
                    }
                    name
                })
                .collect();
            let head = if all_types { "import type " } else { "import " };
            let tail = format!(" from \"{}\";", self.specifier(module));
            write_import(&mut b, head, &names, &tail);
        }
        b
    }

    /// Returns how the file imports `module`: a package by its specifier,
    /// and a generated file by its path relative to this file, ending with
    /// `.js`.
    fn specifier(&self, module: &Module) -> String {
        if !module.generated() {
            return module.as_str().to_owned();
        }
        let from: Vec<&str> = match self.module.as_str().rsplit_once('/') {
            Some((dir, _)) => dir.split('/').collect(),
            None => Vec::new(),
        };
        let to: Vec<&str> = module.as_str().split('/').collect();
        let mut shared = 0;
        while shared < from.len() && shared < to.len() - 1 && from[shared] == to[shared] {
            shared += 1;
        }
        let mut parts = vec![".."; from.len() - shared];
        parts.extend(&to[shared..]);
        let joined = parts.join("/");
        let spec = format!("{}.js", joined.strip_suffix(".ts").unwrap_or(&joined));
        if spec.starts_with("../") {
            spec
        } else {
            format!("./{spec}")
        }
    }
}

impl plugin::File for File {
    fn path(&self) -> &str {
        self.module.as_str()
    }

    /// Returns the preamble, the imports, then the lines printed to the
    /// file, or nothing if nothing was printed. It never fails.
    ///
    /// The imports list packages first, then generated files, each sorted by
    /// specifier, with one declaration per module. A module whose names are
    /// all only types is imported with `import type`, and a name used both
    /// as a type and as a value is imported as a value. If an imported name
    /// clashes with one the file declares or an earlier import, it gets an
    /// alias with `$` appended.
    fn content(&self) -> Result<Cow<'_, [u8]>, Err> {
        Ok(Cow::Owned(self.render().into_bytes()))
    }
}

/// The identifiers a file imports.
struct Imports {
    /// Each imported identifier once, sorted.
    sorted: Vec<Ident>,
    /// The identifiers used as values, and not only as types.
    values: HashSet<Ident>,
}

/// Returns the key `id` is imported under: the root of its name, with
/// `type_only` cleared.
fn import_key(id: &Ident) -> Ident {
    Ident {
        name: Cow::Owned(root(&id.name).to_owned()),
        module: id.module.clone(),
        type_only: false,
        alias: id.alias.clone(),
    }
}

/// Returns the name a dotted name such as `Temporal.Instant` is imported
/// by.
fn root(name: &str) -> &str {
    name.split_once('.').map_or(name, |(root, _)| root)
}

/// Puts packages before generated files.
fn rank(module: &Module) -> u8 {
    u8::from(module.generated())
}

/// Writes an import declaration: on one line when it fits in 80 columns or
/// has one name, and with a name on each line otherwise.
fn write_import(b: &mut String, head: &str, names: &[String], tail: &str) {
    let line = format!("{head}{{ {} }}{tail}", names.join(", "));
    if names.len() == 1 || line.len() <= WIDTH {
        b.push_str(&line);
        b.push('\n');
        return;
    }
    b.push_str(head);
    b.push_str("{\n");
    for name in names {
        b.push_str(INDENT);
        b.push_str(name);
        b.push_str(",\n");
    }
    b.push('}');
    b.push_str(tail);
    b.push('\n');
}

/// Returns `line` after `prefix`, with words wrapped to fit in `WIDTH`
/// columns. Leading spaces, such as a list item's indent, are repeated on
/// each wrapped line.
fn wrap(prefix: &str, line: &str) -> Vec<String> {
    let line = line.trim_end_matches([' ', '\t']);
    let lead = &line[..line.len() - line.trim_start_matches([' ', '\t']).len()];
    let mut words = line.split_whitespace();
    let Some(first) = words.next() else {
        return vec![prefix.trim_end_matches(' ').to_owned()];
    };
    let mut lines = Vec::new();
    let mut current = format!("{prefix}{lead}{first}");
    let mut columns = current.chars().count();
    for word in words {
        let width = word.chars().count();
        if columns + 1 + width <= WIDTH {
            current.push(' ');
            current.push_str(word);
            columns += 1 + width;
            continue;
        }
        lines.push(current);
        current = format!("{prefix}{lead}{word}");
        columns = current.chars().count();
    }
    lines.push(current);
    lines
}
